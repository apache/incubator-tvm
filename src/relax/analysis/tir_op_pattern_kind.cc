class PatternKindAnalyzer : public s_tir::StmtExprVisitor {
 public:
  explicit PatternKindAnalyzer(const tirx::Function& func) {
    for (const tvm::Var& param : func->params) {
      ffi::Optional<TensorVar> param_buf = param.as<TensorVar>();
      if (param_buf.has_value()) {
        param_tensors_.insert(param_buf.value());
      }
    }
  }

 private:
  bool IsOutputBlock(const s_tir::SBlockObj* block) {
    for (const TensorRegion& write_region : block->writes) {
      if (param_tensors_.count(write_region->source.as_or_throw<tvm::tirx::TensorVar>())) {
        return true;
      }
    }
    return false;
  }

  ffi::Optional<VisitInterrupt> Visit_(const TensorStoreObj* op) final {
    // We only support one tensor store in a block (usually generated by TE compute)
    // If we have already seen tensor store in the current block, classify as Opaque.
    if (store_.has_value() && !IsSameArray(op->indices, store_.value()->indices)) {
      kind_ = kOpaque;
      return std::nullopt;
    }
    store_ = ffi::GetRef<TensorStore>(op);
    return s_tir::StmtExprVisitor::Visit_(op);
  }

  ffi::Optional<VisitInterrupt> Visit_(const TensorLoadObj* op) final {
    loads_.push_back(ffi::GetRef<TensorLoad>(op));
    return s_tir::StmtExprVisitor::Visit_(op);
  }

  ffi::Optional<VisitInterrupt> Visit_(const s_tir::SBlockObj* op) final {
    if (op->name_hint == "root") {
      // Skip the root block
      return s_tir::StmtExprVisitor::Visit(op->body);
    }

    // Step 1. Clear loads and store
    loads_.clear();
    store_ = std::nullopt;
    // Step 2. Visit block body.
    TVM_FFI_S_VISIT_MAYBE_EARLY_RETURN(s_tir::StmtExprVisitor::Visit(op->body));

    // We support exactly one tensor store in a block (usually generated by TE compute)
    // If we have not seen any store in the current block, classify as Opaque.
    if (!store_.has_value()) {
      kind_ = kOpaque;
      return std::nullopt;
    }

    TensorStore store = store_.value();

    // Step 3. Checking load store indices pattern
    OpPatternKind index_pair_pattern = kElemWise;
    bool has_elem_wise = false;
    for (const TensorLoad& load : loads_) {
      // Since elemwise is stricter than broadcast and broadcast is stricter than injective,
      // while the order amount enums: kElemWise < kBroadcast < kInjective.
      // We can simply use `std::max` to detect these three patterns.
      // E.g Here is only one store node but two load nodes, like C[i, j] = A[i, j] + B[i]
      // TensorVar C and A are elemwise but C and B are broadcast. So the whole block follows
      // broadcast pattern.
      if (IsElemwisePattern(store, load)) {
        index_pair_pattern = std::max(index_pair_pattern, kElemWise);
        has_elem_wise = true;
      } else if (IsBroadcastPattern(store, load)) {
        index_pair_pattern = std::max(index_pair_pattern, kBroadcast);
      } else if (IsInjectivePattern(store, load)) {
        index_pair_pattern = std::max(index_pair_pattern, kInjective);
      } else {
        index_pair_pattern = kOpaque;
        break;
      }
    }
    // If there is a index pair is kElemWise and others are kBroadcast, we regard it as kElemWise
    // e.g. A[i, j] = B[i, j] + C[i]
    if (index_pair_pattern == kBroadcast && has_elem_wise) {
      index_pair_pattern = kElemWise;
    }
    // If the block index pattern is not opaque, update kind.
    if (index_pair_pattern != kOpaque) {
      // This rule for softmax: reduce + injective.
      if (IsOutputBlock(op) && kind_ == kCommReduce) {
        kind_ = kOutEWiseFusable;
      } else {
        kind_ = std::max(kind_, index_pair_pattern);
      }
      return std::nullopt;
    }

    // Step 4. Checking if the block contains reduce axis by looking into block iterators.
    bool has_reduction = false;
    ffi::Array<tvm::Var> reduce_vars;
    for (const s_tir::IterVar& it : op->iter_vars) {
      if (it->iter_type == s_tir::IterVarType::kCommReduce) {
        has_reduction = true;
        reduce_vars.push_back(it->var);
      }
    }

    if (has_reduction) {
      if (IsFMA(op->body)) {
        // FMA is regards as kOutEWiseFusable, e.g. Matmul or Conv.
        kind_ = std::max(kind_, kOutEWiseFusable);
        return std::nullopt;
      } else {
        for (size_t i = 0; i < loads_.size(); ++i) {
          // If it's not a pure reduce, regards as kOutEWiseFusable.
          // This rule works for pooling for now.
          if (!IsPureReducePattern(reduce_vars, loads_[i]->indices)) {
            kind_ = std::max(kind_, kOutEWiseFusable);
            return std::nullopt;
          }
        }
      }
      kind_ = std::max(kind_, kCommReduce);
    } else {
      kind_ = kOpaque;
    }

    return std::nullopt;
  }

  /********** Helper Functions **********/

  /*! \brief Checking if two arrays contains same elements. */
  static bool IsSameArray(const ffi::Array<PrimExpr>& lhs, const ffi::Array<PrimExpr>& rhs) {
    if (lhs.size() != rhs.size()) {
      return false;
    }
    for (size_t i = 0; i < lhs.size(); ++i) {
      if (!lhs[i].same_as(rhs[i])) {
        return false;
      }
    }
    return true;
  }

  /*!
   * \brief Checking the load indices and store indices follows elemwise pattern.
   * It's elemwise pattern iff load indices and store indices are the same.
   * E.g A[i, j] = B[i, j]
   */
  static bool IsElemwisePattern(const TensorStore& store, const TensorLoad& load) {
    return IsSameArray(store->indices, load->indices);
  }

  /*!
   * \brief Checking the load indices and store indices follows broadcast pattern.
   * It's broadcast pattern iff all load indices are in the store indices in order
   * E.g. A[i, j] = B[i] is broadcast since all load indices(`i`) are in the store indices
   *      A[i, j] = B[i, k] is not broadcast since `k` are not in the store indices.
   *      A[i, j] = B[j, i] is not broadcast the load indices are not in the same order as store's
   */
  static bool IsBroadcastPattern(const TensorStore& store, const TensorLoad& load) {
    size_t ndim_load_buf = load->source.as_or_throw<tvm::tirx::TensorVar>().shape().size();
    size_t ndim_store_buf = store->dest.as_or_throw<tvm::tirx::TensorVar>().shape().size();

    for (size_t i = 0, j = 0; i < ndim_load_buf; ++i) {
      if (IsConstInt(load->source.as_or_throw<tvm::tirx::TensorVar>().shape()[i], 1) &&
          IsConstInt(load->indices[i], 0)) {
        // Skip unit load dimensions
        // E.g. A[i, j] = B[1, j] is still broadcast
        continue;
      }

      // Try to find the i-th load index in the store indices.
      while (j < ndim_store_buf && !store->indices[j].same_as(load->indices[i])) {
        ++j;
      }

      // It's not broadcast if we cannot find load indices in the store indices in order.
      if (j == ndim_store_buf) {
        return false;
      }
    }
    return true;
  }

  /*!
   * \brief Checking the load indices and store indices follows injective pattern.
   * It's injective pattern iff all load index vars are in the store indices, no matter orders.
   * Note that we only support store indices are direct vars so far, which can be enhance later.
   * E.g. A[i, j] = B[j, i] is injective.
   *      A[i, j] = B[i - j] is injective since the load index vars are only i, j
   */
  static bool IsInjectivePattern(const TensorStore& store, const TensorLoad& load) {
    std::unordered_set<const tvm::VarObj*> vars;
    for (const PrimExpr& store_index : store->indices) {
      if (auto var = store_index.as<PrimVar>()) {
        vars.insert(var.value().get());
      } else {
        return false;
      }
    }
    auto walkfn = [&vars](const tvm::Var& var) -> ffi::Expected<ffi::WalkResult> {
      return !vars.count(var.get()) ? ffi::WalkResult::Interrupt(ffi::VisitInterrupt(var))
                                    : ffi::WalkResult::Advance();
    };
    for (const PrimExpr& load_index : load->indices) {
      // return false if there are vars used in load indices but not in store indices.
      if (ffi::StructuralWalk<ffi::WalkOrder::kPreOrder>(load_index, walkfn).has_value()) {
        return false;
      }
    }
    return true;
  }

  /*!
   * \brief Checking the load indices and store indices allow data reuse.
   * It allow data reuse iff there is any vars in load indices but they are not in store indices
   * E.g. Store = A[i, j] and Load = B[i, j, k] allow data reuse.
   *      Store = A[i, j] and Load = B[i, j + k] allow data reuse.
   */
  static bool IsAllowReusePattern(const TensorStore& store, const TensorLoad& load) {
    std::unordered_set<const tvm::VarObj*> vars;
    for (const PrimExpr& index : store->indices) {
      if (auto var = index.as<PrimVar>()) {
        vars.insert(var.value().get());
      } else {
        return false;
      }
    }
    auto walk_fn = [&](const tvm::Var& var) -> ffi::Expected<ffi::WalkResult> {
      if (auto prim_var = var.as<PrimVar>()) {
        vars.erase(prim_var.value().get());
      }
      return ffi::WalkResult::Advance();
    };
    for (const PrimExpr& index : load->indices) {
      ffi::StructuralWalk<ffi::WalkOrder::kPreOrder>(index, walk_fn);
    }
    return !vars.empty();
  }

  static PrimExpr RemoveCast(PrimExpr e) {
    for (;;) {
      if (const auto* cast = e.as<prim::CastObj>()) {
        e = cast->value;
      } else {
        break;
      }
    }
    return e;
  }

  /*! \brief Checking if the stmt is multiply add. E.g. C[i, j] += A[i, k] * B[j, k] */
  static bool IsFMA(const SeqStmt& body) {
    if (body->size() != 1) return false;
    if (const auto* store = body->seq[0].as<TensorStoreObj>()) {
      if (const auto* add = RemoveCast(store->value).as<prim::AddObj>()) {
        if (const auto* mul = RemoveCast(add->b).as<prim::MulObj>()) {
          const auto* store_lhs = RemoveCast(add->a).as<TensorLoadObj>();
          if (!store_lhs ||
              !store->dest.same_as(store_lhs->source.as_or_throw<tvm::tirx::TensorVar>()) ||
              !IsSameArray(store->indices, store_lhs->indices)) {
            return false;
          }
          const auto* lhs = RemoveCast(mul->a).as<TensorLoadObj>();
          const auto* rhs = RemoveCast(mul->b).as<TensorLoadObj>();
          if (!lhs || !rhs) {
            return false;
          }
          return IsAllowReusePattern(ffi::GetRef<TensorStore>(store),
                                     ffi::GetRef<TensorLoad>(lhs)) &&
                 IsAllowReusePattern(ffi::GetRef<TensorStore>(store), ffi::GetRef<TensorLoad>(rhs));
        }
      }
    }
    return false;
  }

  /*!
   * \brief Checking if it is pure reduce pattern.
   * It's pure reduce pattern iff all reduces axis are directly reduce var
   * E.g. A[i] = sum(B[i, j]) is pure reduce
   *      A[i] = sum(B[i, j + k]) is not pure reduce
   *      pooling is not pure reduce
   */
  static bool IsPureReducePattern(ffi::Array<tvm::Var> reduce_loops, ffi::Array<PrimExpr> indices) {
    auto walkfn = [&](const tvm::Var& var) -> ffi::Expected<ffi::WalkResult> {
      return std::any_of(reduce_loops.begin(), reduce_loops.end(),
                         [&](const tvm::Var& loop) { return loop.same_as(var); })
                 ? ffi::WalkResult::Interrupt(ffi::VisitInterrupt(var))
                 : ffi::WalkResult::Advance();
    };
    for (const PrimExpr& e : indices) {
      auto result = ffi::StructuralWalk<ffi::WalkOrder::kPreOrder>(e, walkfn);
      if (result.has_value()) {
        tvm::Var var = result.value()->value.cast<tvm::Var>();
        int id =
            std::distance(reduce_loops.begin(),
                          std::find_if(reduce_loops.begin(), reduce_loops.end(),
                                       [&](const tvm::Var& loop) { return loop.same_as(var); }));
        if (!reduce_loops[id].same_as(e)) {
          return false;
        }
      }
    }
    return true;
  }

 private:
  /*!
   * \brief The TensorStore node in the current block.
   * \note We only support one TensorStore node in a block (usually generated by TE compute)
   */
  ffi::Optional<TensorStore> store_;
  /*! \brief The TensorLoad nodes in the current block. */
  ffi::Array<TensorLoad> loads_;
  /*! \brief The result of op pattern. */
  OpPatternKind kind_ = kElemWise;
  /*! \brief The tensors from function params. I.e. the input and output tensors. */
  std::unordered_set<TensorVar, ffi::ObjectPtrHash, ffi::ObjectPtrEqual> param_tensors_;

 public:
  OpPatternKind GetResult() { return kind_; }
};

OpPatternKind AnalyzeOpPatternKind(const tirx::Function& func) {
  auto analyzer = ffi::make_object<PatternKindAnalyzer>(func);
  analyzer->Visit(func->body);
  return analyzer->GetResult();
}

bool HasReshapePattern(const tirx::Function& func) {
  if (!func->body.has_value()) return false;
  class ReshapeDetector : public s_tir::StmtExprVisitor {
   public:
    ffi::Optional<VisitInterrupt> Visit(ffi::AnyView value) override {
      if (value.as<tvm::ExprObj>()) return std::nullopt;
      return s_tir::StmtExprVisitor::Visit(value);
    }

    static bool Detect(const TensorVar& src_tensor, const TensorVar& dst_tensor, Stmt stmt) {
      auto detector = ffi::make_object<ReshapeDetector>(src_tensor, dst_tensor);
      detector->Visit(stmt);
      return detector->is_reshape_;
    }

    explicit ReshapeDetector(const TensorVar& src_tensor, const TensorVar& dst_tensor)
        : is_reshape_(false), src_tensor_(src_tensor), dst_tensor_(dst_tensor) {}

   private:
    ffi::Optional<VisitInterrupt> Visit_(const ForObj* loop) final {
      auto context = ana_->GetConstraintContext();
      context->Append(sym::RangeConstraint(loop->var, Range(loop->begin, loop->end)));
      ana_->SyncConstraintContext(context);
      // To detect the reshape pattern, we require each For to have
      // either another For or a BlockRealize as body.
      if (loop->body->size() != 1 || !(loop->body->seq[0]->IsInstance<ForObj>() ||
                                       loop->body->seq[0]->IsInstance<s_tir::SBlockRealizeObj>())) {
        return std::nullopt;
      }
      return this->Visit(loop->body);
    }

    ffi::Optional<VisitInterrupt> Visit_(const s_tir::SBlockRealizeObj* block_realize) final {
      // Constructing the mapping from block iterators to iterator
      // binding values. The mapping will be used in the substitution of
      // the flattened tensor access index.
      const s_tir::SBlock& block = block_realize->block;
      const ffi::Array<s_tir::IterVar>& block_iter = block->iter_vars;
      const ffi::Array<PrimExpr>& iter_values = block_realize->iter_values;
      TVM_FFI_ICHECK_EQ(block_iter.size(), iter_values.size());
      int n_iter = block_iter.size();
      for (int i = 0; i < n_iter; ++i) {
        // To detect the reshape pattern, we require each block iter to be data-parallel.
        if (block_iter[i]->iter_type != s_tir::IterVarType::kDataPar) {
          return std::nullopt;
        }
      }

      // Recurse into the block.
      return this->Visit(block);
    }

    ffi::Optional<VisitInterrupt> Visit_(const s_tir::SBlockObj* block) final {
      if (block->body->size() != 1) return std::nullopt;
      // Step 0. If the block body is a ForObj, recurse into it.
      if (block->body->seq[0]->IsInstance<ForObj>()) {
        return this->Visit(block->body);
      }

      ffi::Map<PrimVar, Range> var_range;
      for (const s_tir::IterVar& v : block->iter_vars) {
        auto context = ana_->GetConstraintContext();
        context->Append(sym::RangeConstraint(v->var, v->dom.value()));
        ana_->SyncConstraintContext(context);
        var_range.Set(v->var, v->dom.value());
      }

      // Step 1. Get the load/store pattern of the block body.
      // To detect the reshape pattern, we require the block body to be a
      // TensorStore, which has a TensorLoad as value.
      const auto* tensor_store = block->body->seq[0].as<TensorStoreObj>();
      if (tensor_store == nullptr) {
        return std::nullopt;
      }
      const auto* tensor_load = tensor_store->value.as<TensorLoadObj>();
      if (tensor_load == nullptr) {
        return std::nullopt;
      }
      // Further, we require the tensor being stored and being loaded to
      // match the parameter of the tirx::Function, namely `dst_tensor_` and `src_tensor_`.
      if (!(tensor_store->dest.same_as(dst_tensor_) &&
            tensor_load->source.as_or_throw<tvm::tirx::TensorVar>().same_as(src_tensor_))) {
        return std::nullopt;
      }

      // Apply check 1: use iter_map_simplify
      // This check requires at least one of the src/dst side is a trivial tensor
      // access (e.g., buf[ax0, ax1, ax2]).

      auto f_calc_flattened_idx = [&](const TensorVar& tensor,
                                      const ffi::Array<PrimExpr>& indices) {
        TVM_FFI_ICHECK_EQ(indices.size(), tensor.shape().size());
        int ndim = indices.size();
        PrimExpr idx = 0;
        for (int i = 0; i < ndim; ++i) {
          idx = idx * tensor.shape()[i] + indices[i];
        }
        idx = ana_->Simplify(idx);
        return sym::IterMapSimplify(
            /*indices=*/{idx},
            /*input_iters=*/var_range,
            /*input_pred=*/IntImm::Bool(true),
            /*check_level=*/sym::IterMapLevel::Surjective,
            /*analyzer=*/ana_,
            /*simplify_trivial_iterators=*/true)[0];
      };

      auto f_is_trivial_indices = [block, this](const TensorVar& tensor,
                                                const ffi::Array<PrimExpr>& indices) {
        if (indices.size() != block->iter_vars.size()) {
          return false;
        }
        for (int i = 0; i < static_cast<int>(block->iter_vars.size()); ++i) {
          if (!(indices[i].same_as(block->iter_vars[i]->var) &&
                this->ana_->CanProveEqual(block->iter_vars[i]->dom.value()->begin,
                                          IntImm::Int64(/*value=*/0)) &&
                this->ana_->CanProveEqual(tensor.shape()[i],
                                          block->iter_vars[i]->dom.value()->extent))) {
            return false;
          }
        }
        return true;
      };

      ffi::Array<PrimExpr> nontrivial_indices;
      ffi::Optional<TensorVar> nontrivial_tensor;
      if (f_is_trivial_indices(dst_tensor_, tensor_store->indices)) {
        nontrivial_indices = tensor_load->indices;
        nontrivial_tensor = src_tensor_;
      } else if (f_is_trivial_indices(src_tensor_, tensor_load->indices)) {
        nontrivial_indices = tensor_store->indices;
        nontrivial_tensor = dst_tensor_;
      }

      // Skip check 1 on zero-extent iters: the inverse index map would divide by zero.
      bool has_zero_extent = std::any_of(
          block->iter_vars.begin(), block->iter_vars.end(), [this](const s_tir::IterVar& v) {
            return this->ana_->CanProveEqual(v->dom.value()->extent, 0);
          });

      if (nontrivial_tensor.has_value() && !has_zero_extent) {
        PrimType dtype =
            !block->iter_vars.empty() ? block->iter_vars[0]->var.ty() : PrimType::Int(64);
        PrimVar fused_var("fused", dtype);
        ffi::Map<tvm::Var, PrimExpr> inverse_indices_map;
        PrimExpr stride = IntImm(dtype, /*value=*/1);
        for (int i = static_cast<int>(block->iter_vars.size()) - 1; i >= 0; --i) {
          inverse_indices_map.Set(block->iter_vars[i]->var,
                                  floormod(floordiv(fused_var.as_or_throw<PrimExpr>(), stride),
                                           block->iter_vars[i]->dom.value()->extent));
          stride *= block->iter_vars[i]->dom.value()->extent;
        }
        auto f_substitute = [&inverse_indices_map](
                                const tvm::Var& var) -> ffi::Expected<ffi::UnchangedOr<ffi::Any>> {
          if (auto repl = inverse_indices_map.Get(var)) return ffi::Any(*std::move(repl));
          return ffi::Unchanged();
        };
        PrimExpr flattened_idx =
            f_calc_flattened_idx(nontrivial_tensor.value(), nontrivial_indices);
        flattened_idx =
            ffi::StructuralMap<ffi::WalkOrder::kPreOrder>(std::move(flattened_idx), f_substitute)
                .as_or_throw<PrimExpr>();

        ffi::Array<PrimExpr> simplify_res = sym::IterMapSimplify(
            /*indices=*/{flattened_idx},
            /*input_iters=*/
            ffi::Map<PrimVar, Range>{{fused_var, Range(IntImm(dtype, /*value=*/0), stride)}},
            /*input_pred=*/IntImm::Bool(true),
            /*check_level=*/sym::IterMapLevel::Surjective,
            /*analyzer=*/this->ana_,
            /*simplify_trivial_iterators=*/true);
        TVM_FFI_ICHECK_EQ(simplify_res.size(), 1);

        if (simplify_res[0].same_as(fused_var)) {
          this->is_reshape_ = true;
          return std::nullopt;
        }
      }

      // Apply check 2 as followup when check 1 is not satisfied.
      // Calculate the flattened access index according to the load/store pattern.
      PrimExpr src_idx = f_calc_flattened_idx(src_tensor_, tensor_load->indices);
      PrimExpr dst_idx = f_calc_flattened_idx(dst_tensor_, tensor_store->indices);
      // Check if we can prove the equality of flattened indices.
      if (ana_->CanProveEqual(src_idx, dst_idx)) {
        this->is_reshape_ = true;
        return std::nullopt;
      }

      return std::nullopt;
    }

    bool is_reshape_;
    const TensorVar& src_tensor_;
    const TensorVar& dst_tensor_;
    sym::Analyzer ana_;
  };

  ffi::Array<TensorVar> tensor_args;
  for (const auto& param : func->params) {
    if (auto tensor = param.as<TensorVar>()) {
      tensor_args.push_back(tensor.value());
    }
  }

  if (tensor_args.size() < 2) {
    return false;
  }
  TensorVar src_tensor = tensor_args.front();
  TensorVar dst_tensor = tensor_args.back();

  // To detect the reshape pattern, we require each For to have
  // either another For or a BlockRealize as body.
  TVM_FFI_ICHECK(func->body.value()->size() == 1 &&
                 func->body.value()->seq[0].as<s_tir::SBlockRealizeObj>());
  return ReshapeDetector::Detect(src_tensor, dst_tensor, func->body.value());
}

TVM_FFI_STATIC_INIT_BLOCK() {
  namespace refl = tvm::ffi::reflection;
  refl::GlobalDef().def("relax.analysis.has_reshape_pattern", HasReshapePattern);
}

